function reportDiagnostics(model, generated){
  const el = document.getElementById('parsewarn');
  if (!el) return;
  const ds = (model && model.diagnostics) || [];
  if (!ds.length) { el.style.display = 'none'; el.innerHTML = ''; return; }
  el.innerHTML = '<button type="button">dismiss</button><b>' + (generated
    ? 'This notation was generated by RagaM-Roll and cannot be read back — that is a bug, please report it.'
    : ds.length + ' part(s) of this notation could not be read as written.') +
    '</b> What is playing instead:<ul>' +
    ds.map(d => `<li>${d.message.replace(/[<&]/g, c => ({'<':'&lt;','&':'&amp;'}[c]))}</li>`).join('') +
    '</ul>';
  el.querySelector('button').onclick = () => { el.style.display = 'none'; };
  el.style.display = '';
}

